# Q8 write a program to swap two number using third variable.

x= int(input('Enter the x value. '))
y= int(input('Enter the y value. '))


temp = x
print('the value of temp variable is', temp)
x=y
print('the value of x is',x)

y = temp
print('the value of temp variable is', y)
x=y
print('the value of y is',x)


